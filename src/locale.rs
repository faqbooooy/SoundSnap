use core::sync::atomic::{AtomicBool, Ordering::Relaxed};
use windows_sys::Win32::Globalization::GetUserDefaultUILanguage;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u8)]
pub enum Language { System, Russian, English }

static ENGLISH: AtomicBool = AtomicBool::new(true);

pub fn apply(language: Language) -> bool {
    const PRIMARY_LANGUAGE_MASK: u16 = 0x03ff;
    const RUSSIAN: u16 = 0x19;
    let english = match language {
        Language::System => unsafe { GetUserDefaultUILanguage() & PRIMARY_LANGUAGE_MASK != RUSSIAN },
        Language::Russian => false,
        Language::English => true,
    };
    ENGLISH.swap(english, Relaxed) != english
}

